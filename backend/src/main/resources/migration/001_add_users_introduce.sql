-- =====================================================================
-- 001. users.introduce 컬럼 추가 (프로필 한줄소개)
--
-- 배경: 프로필 설정 API(POST /api/profiles)가 한줄소개를 저장하는데
--       기존 DB에는 컬럼이 없었다. schema.sql은 DB를 새로 만들 때만
--       실행되므로, 이미 만들어진 DB에는 아래 ALTER를 직접 실행해야 한다.
--
-- 적용 상태:
--   [x] 운영 서버(i15e204) — 2026-07-29 적용 완료
--   [ ] 각자 로컬 — 아래 실행 필요 (도커 볼륨을 새로 만들면 불필요)
-- =====================================================================

ALTER TABLE users
    ADD COLUMN introduce VARCHAR(255) NULL COMMENT '한줄소개 (프로필 생성 단계에서 설정)'
    AFTER profile_image_url;

