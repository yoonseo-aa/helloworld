-- =====================================================================
-- 003. users.exp_point / level 컬럼 제거 (미사용 레벨 기능)
--
-- 배경: 레벨/경험치 기능 미사용으로 users.exp_point, users.level 컬럼을
--       제거했다(schema.sql·UserMapper·User 엔티티 반영). schema.sql은
--       DB를 새로 만들 때만 실행되므로, 이미 만들어진 DB에는 아래 ALTER를
--       직접 실행해 스키마를 맞춰야 한다.
--
--       참고: 두 컬럼은 미사용(비즈니스 로직에서 읽지 않음)이라, 서버 DB에
--       컬럼이 남아 있어도 앱 동작 자체엔 문제가 없다(INSERT는 컬럼을 빼고
--       하며 SELECT도 참조 안 함). 이 마이그레이션은 스키마 정합을 위한 것.
--
-- ⚠️ DROP COLUMN은 되돌릴 수 없다(컬럼·데이터 삭제). 단 두 컬럼은
--    DEFAULT 0/1로만 채워진 미사용 값이라 잃는 데이터가 없다.
--
-- 적용 상태:
--   [x] 운영 서버(i15e204) — 2026-07-31 적용 완료
--   [ ] 각자 로컬 — 아래 실행 필요 (도커 볼륨을 새로 만들면 불필요)
-- =====================================================================

ALTER TABLE users
    DROP COLUMN exp_point,
    DROP COLUMN level;

