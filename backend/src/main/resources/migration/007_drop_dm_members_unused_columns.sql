-- =====================================================================
-- 007. dm_members 미사용 컬럼 제거 (is_accepted, is_muted)
--
-- 배경: 두 컬럼 모두 "만들 예정이었던 기능"을 위해 미리 넣어둔 것인데,
--       팀 논의로 그 기능을 만들지 않기로 확정되어 쓰이지 않는다.
--
--   is_accepted — 인스타그램식 '메시지 요청'(모르는 사람의 첫 메시지를 수락해야 대화 시작).
--                 "모르는 사람도 바로 대화할 수 있다"로 확정 → 이 상태값이 필요 없다.
--                 코드에서도 항상 기본값(TRUE)으로만 들어갔고 읽는 곳이 없었다.
--   is_muted    — 알림 끄기(mute). 기능을 만들지 않기로 확정.
--                 (안읽음 수는 mute와 무관하게 세야 하므로 조회 쿼리에도 쓰이지 않았다)
--
-- 쓰지 않는 컬럼을 남겨두면 다음 사람이 "이 값에 따라 분기해야 하나?"를 매번 확인해야 하고,
-- ERD와 실제 동작이 어긋난 채로 굳는다. 기능이 없다는 결정이 확정된 지금 지우는 게 맞다.
--
-- ⚠️ 적용 순서: 코드 배포가 먼저다.
--   컬럼 삭제는 "코드 먼저 → DB 나중". 반대로 하면 아직 그 컬럼을 참조하는 이전 버전 앱이
--   조회에서 500을 낸다. (컬럼 추가는 그 반대로 DB가 먼저다)
--   이 스크립트는 해당 코드 변경이 develop에 머지·배포된 뒤에 실행한다.
--
-- 되돌리기 (필요하면):
--   ALTER TABLE dm_members
--       ADD COLUMN is_accepted BOOLEAN NOT NULL DEFAULT TRUE  COMMENT 'false=메시지 요청 대기',
--       ADD COLUMN is_muted    BOOLEAN NOT NULL DEFAULT FALSE;
--   기본값이 있는 컬럼이라 되돌려도 기존 행이 그대로 채워진다(데이터 손실 없음).
--
-- 적용: 운영 DB / 각자 로컬 DB에 한 번씩 실행
-- =====================================================================

ALTER TABLE dm_members
    DROP COLUMN is_accepted,
    DROP COLUMN is_muted;
