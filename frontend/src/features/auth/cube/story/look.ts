  //
  // 예전엔 균형 잡힌 3/4 인물 조명이었다 — 키 132°/40°에 0.85, 림은 기본값, 필 0.6.
  // 정확하고 잘 읽히고 전혀 신비롭지 않았다. 모든 면이 해석되어 있어서 눈이 마저 채울
