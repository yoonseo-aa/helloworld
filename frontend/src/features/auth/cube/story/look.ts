  // 한쪽으로 치우쳐 달린 스팟이 비추고, 그 거리가 가까워서 주변 무엇보다 물건이 밝다.
  // 방은 어두운 채로 두고, 물건이 받지 못한 빛은 그냥 사라진다. 그래서 세 조명은 낮추는
