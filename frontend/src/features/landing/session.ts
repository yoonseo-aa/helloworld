/**
 * 이 페이지 로드에서 인트로를 건너뛸지.
 *
 * 메인(`/`)으로 온 비로그인 방문자를 `/welcome`으로 보낼지 정하는 데만 쓴다. 판정하는 곳은
 * `RouteGuards`의 메인 분기 한 곳뿐이고, `/welcome`을 직접 열거나 뒤로가기로 돌아왔을 때는
 * 이 값을 보지 않는다 — 주소로 명시한 방문까지 막으면 뒤로가기가 빈 화면이 된다.
 *
 * **왜 저장소가 아니라 메모리인가.** 이 값이 존재하는 이유는 딱 하나, 피드를 보다 세션이
 * 끊기는 순간을 걸러내기 위해서다. 그때 경로는 여전히 `/`이고 토큰만 사라지므로, 조건이
 * 없으면 글 읽던 사람이 4씬 인트로로 튕긴다. 그런데 그 상황은 **같은 페이지 로드 안에서**
 * 벌어진다 — 토큰을 가졌던 것도, 잃은 것도 한 로드 안이다. 그러니 기록도 그 수명이면
 * 충분하다.
 *
 * sessionStorage였을 때는 탭이 죽을 때까지 남아서, 로그아웃하고 다시 `/`로 와도 인트로가
 * 안 떴다. 주소창에 도메인을 치는 것도 새 페이지 로드인데 탭은 그대로라 마찬가지였다.
 * 걸러야 할 것보다 훨씬 많이 걸러낸 셈이다.
 *
 * 메모리면 새로고침·주소창 입력·새 탭이 전부 초기화라 "메인으로 오면 인트로"가 성립하고,
 * 세션 만료만 정확히 걸러진다.
 */
let introDone = false

export function isIntroDone() {
  return introDone
}

export function markIntroDone() {
  introDone = true
}
